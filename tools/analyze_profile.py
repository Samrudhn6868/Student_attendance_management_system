"""Analyze profiling data and display top slowest functions.

This script reads .prof files generated by profile_app.py and provides
human-readable analysis of performance bottlenecks.

Usage:
    python tools/analyze_profile.py <profile_file> [--top N] [--sort {cumulative,tottime,calls}]
    python tools/analyze_profile.py reports/profiles/student_dashboard.prof
    python tools/analyze_profile.py reports/profiles/*.prof --top 20
"""

import pstats
import argparse
import os
import glob
from io import StringIO


def analyze_profile(profile_file, top_n=30, sort_by='cumulative'):
    """Analyze a single profile file.
    
    Args:
        profile_file: Path to .prof file
        top_n: Number of top functions to display
        sort_by: Sort criterion (cumulative, tottime, calls, etc.)
    """
    if not os.path.exists(profile_file):
        print(f"✗ Error: Profile file not found: {profile_file}")
        return False
    
    print(f"\n{'='*80}")
    print(f"PROFILE ANALYSIS: {os.path.basename(profile_file)}")
    print(f"{'='*80}\n")
    
    # Load profile stats
    stats = pstats.Stats(profile_file)
    
    # Print basic statistics
    print(f"Total function calls: {stats.total_calls:,}")
    print(f"Primitive calls: {stats.prim_calls:,}")
    print(f"Total time: {stats.total_tt:.3f} seconds\n")
    
    # Top functions by specified criterion
    print(f"{'='*80}")
    print(f"TOP {top_n} FUNCTIONS (sorted by {sort_by})")
    print(f"{'='*80}")
    
    stats.sort_stats(sort_by)
    stats.print_stats(top_n)
    
    # Additional insights
    print(f"\n{'='*80}")
    print("PERFORMANCE INSIGHTS")
    print(f"{'='*80}\n")
    
    # Capture stats to string for analysis
    stream = StringIO()
    stats_copy = pstats.Stats(profile_file, stream=stream)
    stats_copy.sort_stats(sort_by)
    stats_copy.print_stats(100)
    stats_output = stream.getvalue()
    
    # Find slow patterns
    insights = []
    
    if 'sqlalchemy' in stats_output.lower():
        insights.append("🔍 SQLAlchemy operations detected - check for N+1 query patterns")
    
    if 'bcrypt' in stats_output.lower():
        insights.append("🔐 Password hashing detected - this is expected to be slow")
    
    if '_read' in stats_output or '_write' in stats_output:
        insights.append("💾 File I/O operations detected")
    
    if 'json' in stats_output.lower():
        insights.append("📝 JSON serialization detected")
    
    # Check for specific bottlenecks
    lines = stats_output.split('\n')
    for line in lines[:50]:  # Check top 50 functions
        if 'encryption' in line.lower():
            insights.append("🔒 Encryption operations detected - consider caching encrypted values")
            break
    
    if insights:
        for insight in insights:
            print(f"  {insight}")
    else:
        print("  ✓ No obvious performance issues detected")
    
    # Print top callers
    print(f"\n{'='*80}")
    print(f"TOP {min(15, top_n)} CALLERS")
    print(f"{'='*80}\n")
    
    stats.print_callers(min(15, top_n))
    
    return True


def compare_profiles(profile_files, top_n=15):
    """Compare multiple profile files side by side.
    
    Args:
        profile_files: List of profile file paths
        top_n: Number of top functions to compare
    """
    print(f"\n{'='*80}")
    print(f"PROFILE COMPARISON ({len(profile_files)} files)")
    print(f"{'='*80}\n")
    
    for profile_file in profile_files:
        if not os.path.exists(profile_file):
            print(f"✗ Skipping missing file: {profile_file}")
            continue
        
        stats = pstats.Stats(profile_file)
        filename = os.path.basename(profile_file)
        
        print(f"\n{filename}:")
        print(f"  Total calls: {stats.total_calls:,}")
        print(f"  Total time: {stats.total_tt:.3f}s")
        
        # Show top 3 slowest functions
        stream = StringIO()
        stats_copy = pstats.Stats(profile_file, stream=stream)
        stats_copy.sort_stats('cumulative')
        stats_copy.print_stats(3)
        
        output_lines = stream.getvalue().split('\n')
        print("  Top 3 functions:")
        for line in output_lines:
            if line.strip() and not line.startswith('   '):
                if any(c.isdigit() for c in line):
                    print(f"    {line.strip()}")


def find_bottlenecks(profile_file, threshold_percent=5.0):
    """Find functions consuming more than threshold% of total time.
    
    Args:
        profile_file: Path to .prof file
        threshold_percent: Minimum percentage of total time to report
    """
    if not os.path.exists(profile_file):
        print(f"✗ Error: Profile file not found: {profile_file}")
        return
    
    print(f"\n{'='*80}")
    print(f"BOTTLENECK ANALYSIS (>{threshold_percent}% of total time)")
    print(f"{'='*80}\n")
    
    stats = pstats.Stats(profile_file)
    total_time = stats.total_tt
    threshold_time = total_time * (threshold_percent / 100.0)
    
    # Get all stats
    stream = StringIO()
    stats_copy = pstats.Stats(profile_file, stream=stream)
    stats_copy.sort_stats('tottime')
    stats_copy.print_stats(100)
    
    print(f"Total execution time: {total_time:.3f}s")
    print(f"Threshold: {threshold_percent}% = {threshold_time:.3f}s\n")
    
    print(f"Functions taking >{threshold_percent}% of total time:")
    print(f"{'-'*80}")
    
    # Parse output to find bottlenecks
    # This is a simplified approach - pstats doesn't provide easy programmatic access
    stats.sort_stats('tottime')
    stats.print_stats(50)  # Print enough to see bottlenecks


def generate_report(profile_file, output_file=None):
    """Generate a comprehensive report from profile data.
    
    Args:
        profile_file: Path to .prof file
        output_file: Optional output file for report (default: stdout)
    """
    if not os.path.exists(profile_file):
        print(f"✗ Error: Profile file not found: {profile_file}")
        return
    
    stats = pstats.Stats(profile_file)
    
    # Determine output
    if output_file:
        output = open(output_file, 'w', encoding='utf-8')
    else:
        output = StringIO()
    
    # Generate report
    output.write(f"PROFILING REPORT\n")
    output.write(f"{'='*80}\n")
    output.write(f"Profile file: {profile_file}\n")
    output.write(f"Total calls: {stats.total_calls:,}\n")
    output.write(f"Primitive calls: {stats.prim_calls:,}\n")
    output.write(f"Total time: {stats.total_tt:.3f} seconds\n")
    output.write(f"{'='*80}\n\n")
    
    # By cumulative time
    output.write("TOP 30 BY CUMULATIVE TIME:\n")
    output.write("-" * 80 + "\n")
    stats_copy = pstats.Stats(profile_file, stream=output)
    stats_copy.sort_stats('cumulative')
    stats_copy.print_stats(30)
    
    output.write("\n\nTOP 30 BY TOTAL TIME:\n")
    output.write("-" * 80 + "\n")
    stats_copy = pstats.Stats(profile_file, stream=output)
    stats_copy.sort_stats('tottime')
    stats_copy.print_stats(30)
    
    output.write("\n\nTOP 20 CALLERS:\n")
    output.write("-" * 80 + "\n")
    stats_copy.print_callers(20)
    
    if output_file:
        output.close()
        print(f"✓ Report saved to: {output_file}")
    else:
        print(output.getvalue())


def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description='Analyze profiling data from .prof files',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Analyze single profile
  python tools/analyze_profile.py reports/profiles/student_dashboard.prof
  
  # Show top 50 functions
  python tools/analyze_profile.py reports/profiles/student_dashboard.prof --top 50
  
  # Sort by total time instead of cumulative
  python tools/analyze_profile.py reports/profiles/student_dashboard.prof --sort tottime
  
  # Compare multiple profiles
  python tools/analyze_profile.py reports/profiles/*.prof --compare
  
  # Find bottlenecks (>10% of time)
  python tools/analyze_profile.py reports/profiles/student_dashboard.prof --bottlenecks --threshold 10
  
  # Generate detailed report to file
  python tools/analyze_profile.py reports/profiles/student_dashboard.prof --report report.txt
        """
    )
    
    parser.add_argument(
        'profile_files',
        nargs='+',
        help='Profile file(s) to analyze (supports wildcards)'
    )
    parser.add_argument(
        '--top',
        type=int,
        default=30,
        help='Number of top functions to display (default: 30)'
    )
    parser.add_argument(
        '--sort',
        choices=['cumulative', 'tottime', 'calls', 'ncalls', 'time'],
        default='cumulative',
        help='Sort criterion (default: cumulative)'
    )
    parser.add_argument(
        '--compare',
        action='store_true',
        help='Compare multiple profile files'
    )
    parser.add_argument(
        '--bottlenecks',
        action='store_true',
        help='Find performance bottlenecks'
    )
    parser.add_argument(
        '--threshold',
        type=float,
        default=5.0,
        help='Threshold percentage for bottleneck detection (default: 5.0)'
    )
    parser.add_argument(
        '--report',
        metavar='OUTPUT_FILE',
        help='Generate comprehensive report to file'
    )
    
    args = parser.parse_args()
    
    # Expand wildcards
    profile_files = []
    for pattern in args.profile_files:
        if '*' in pattern or '?' in pattern:
            profile_files.extend(glob.glob(pattern))
        else:
            profile_files.append(pattern)
    
    if not profile_files:
        print("✗ Error: No profile files found")
        return 1
    
    # Execute requested operation
    if args.compare and len(profile_files) > 1:
        compare_profiles(profile_files, args.top)
    elif args.bottlenecks:
        for profile_file in profile_files:
            find_bottlenecks(profile_file, args.threshold)
    elif args.report:
        for profile_file in profile_files:
            output = args.report if len(profile_files) == 1 else f"{os.path.splitext(args.report)[0]}_{os.path.basename(profile_file)}.txt"
            generate_report(profile_file, output)
    else:
        # Standard analysis
        for profile_file in profile_files:
            if not analyze_profile(profile_file, args.top, args.sort):
                continue
    
    print("\n✓ Analysis complete!")
    return 0


if __name__ == '__main__':
    exit(main())
